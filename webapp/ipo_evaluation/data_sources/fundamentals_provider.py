from __future__ import annotations

from typing import Any, Protocol

from ..models.security import SecurityIdentity


class FundamentalsProvider(Protocol):
    def get_company_profile(self, identity: SecurityIdentity) -> dict[str, Any]: ...
    def get_annual_income_statements(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_quarterly_income_statements(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_balance_sheets(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_cash_flow_statements(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_ratios(self, identity: SecurityIdentity) -> dict[str, Any]: ...
    def get_shareholding(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_corporate_actions(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
    def get_peer_list(self, identity: SecurityIdentity) -> list[dict[str, Any]]: ...
